                '    },\n',
                '    {\n',
                '        "category": "Notice Period",\n',
                '        "query": "What is the required notice period for termination, renewal, or modification?",\n',
                '        "keywords": ["notice", "days", "written notice", "prior notice", "promptly", "notice period", "calendar days"],\n',
                '    },\n',
                '    {\n',
                '        "category": "Liability Caps",\n',
                '        "query": "What are the limitation of liability, liability caps, or indemnification limits?",\n',
                '        "keywords": ["liability", "limitation of liability", "indemnify", "indemnification", "cap", "aggregate liability", "consequential damages"],\n',
                '    },\n',
                ']\n',
                '\n',
                'def tokenize(text: str) -> List[str]:\n',
                '    return re.findall(r"\\w+", text.lower()) if text else []\n',
                '\n',
                'def run_variant_search(\n',
                '    query: str,\n',
                '    chunks: List[Dict[str, Any]],\n',
                '    chunk_embeddings: np.ndarray,\n',
                '    model: Any,\n',
                '    dense_weight: float = 0.7,\n',
                '    bm25_weight: float = 0.3,\n',
                '    top_k: int = 5,\n',
                ') -> List[Dict[str, Any]]:\n',
                '    if not chunks:\n',
                '        return []\n',
                '\n',
                '    # Dense Cosine Similarity\n',
                '    if dense_weight > 0 and chunk_embeddings is not None and len(chunk_embeddings) > 0:\n',
                '        query_vector = model.encode(query, normalize_embeddings=True)\n',
                '        dense_scores = np.dot(chunk_embeddings, query_vector)\n',
                '        min_d, max_d = float(dense_scores.min()), float(dense_scores.max())\n',
                '        dense_norm = (dense_scores - min_d) / (max_d - min_d) if max_d > min_d else np.zeros_like(dense_scores)\n',
                '    else:\n',
                '        dense_norm = np.zeros(len(chunks), dtype=float)\n',
                '\n',
                '    # Sparse BM25 Scoring\n',
                '    if bm25_weight > 0:\n',
                '        corpus = [tokenize(c["text"] + " " + c["parent_text"]) for c in chunks]\n',
                '        q_tokens = tokenize(query)\n',
                '        if any(corpus) and q_tokens:\n',
                '            bm25 = BM25Okapi(corpus)\n',
                '            raw_bm25 = np.array(bm25.get_scores(q_tokens), dtype=float)\n',
                '            min_bm, max_bm = float(raw_bm25.min()), float(raw_bm25.max())\n',
                '            bm25_norm = (raw_bm25 - min_bm) / (max_bm - min_bm) if max_bm > min_bm else np.zeros_like(raw_bm25)\n',
                '        else:\n',
                '            bm25_norm = np.zeros(len(chunks), dtype=float)\n',
                '    else:\n',
                '        bm25_norm = np.zeros(len(chunks), dtype=float)\n',
                '\n',
                '    scores = (dense_weight * dense_norm) + (bm25_weight * bm25_norm)\n',
                '    top_indices = np.argsort(scores)[::-1][:top_k]\n',
                '    \n',
                '    results = []\n',
                '    for idx in top_indices:\n',
                '        res = dict(chunks[idx])\n',
                '        res["score"] = float(scores[idx])\n',
                '        results.append(res)\n',
                '    return results\n',
                '\n',
                'def is_chunk_relevant(chunk: Dict[str, Any], keywords: List[str]) -> bool:\n',
                '    combined = (chunk["text"] + " " + chunk.get("parent_text", "")).lower()\n',
                '    return any(kw in combined for kw in keywords)\n',
                '\n',
                'def verify_quote_grounding(quote: str, doc_text: str) -> bool:\n',
                '    if not quote or not doc_text:\n',
                '        return False\n',
                '    clean_q = re.sub(r"[^a-zA-Z0-9]", "", quote).lower()\n',
                '    clean_doc = re.sub(r"[^a-zA-Z0-9]", "", doc_text).lower()\n',
                '    return clean_q[:25] in clean_doc if len(clean_q) >= 5 else clean_q in clean_doc\n',
                '\n',
                'print("Ablation search variations configured successfully.")'
