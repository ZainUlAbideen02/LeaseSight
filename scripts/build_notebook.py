                '\n',
                'def extract_pdf_layout(pdf_path: Path) -> Dict[str, Any]:\n',
                '    spatial_data = {"file_name": pdf_path.name, "pages": []}\n',
                '    reader = PdfReader(str(pdf_path))\n',
                '    for idx, page in enumerate(reader.pages, start=1):\n',
                '        text = page.extract_text() or ""\n',
                '        lines = [line.strip() for line in text.splitlines() if line.strip()]\n',
                '        spatial_data["pages"].append({\n',
                '            "page_number": idx,\n',
                '            "lines": lines,\n',
                '            "text": text,\n',
                '        })\n',
                '    return spatial_data\n',
                '\n',
                'def create_parent_child_chunks(spatial_data: Dict[str, Any], child_size: int = 250) -> List[Dict[str, Any]]:\n',
                '    file_name = spatial_data["file_name"]\n',
                '    chunks = []\n',
                '    for page in spatial_data["pages"]:\n',
                '        page_num = page["page_number"]\n',
                '        page_text = page["text"] or " ".join(page.get("lines", []))\n',
                '        if not page_text.strip():\n',
                '            continue\n',
                '        parent_id = f"{file_name}_p{page_num}"\n',
                '        if len(page_text) <= child_size:\n',
                '            chunks.append({\n',
                '                "id": f"{parent_id}_c0",\n',
                '                "file_name": file_name,\n',
                '                "page_number": page_num,\n',
                '                "parent_id": parent_id,\n',
                '                "text": page_text,\n',
                '                "parent_text": page_text,\n',
                '            })\n',
                '        else:\n',
                '            c_idx = 0\n',
                '            for start_pos in range(0, len(page_text), child_size):\n',
                '                c_text = page_text[start_pos : start_pos + child_size]\n',
                '                if c_text.strip():\n',
                '                    chunks.append({\n',
                '                        "id": f"{parent_id}_c{c_idx}",\n',
                '                        "file_name": file_name,\n',
                '                        "page_number": page_num,\n',
                '                        "parent_id": parent_id,\n',
                '                        "text": c_text,\n',
                '                        "parent_text": page_text,\n',
                '                    })\n',
                '                    c_idx += 1\n',
